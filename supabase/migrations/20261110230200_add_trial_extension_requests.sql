create table if not exists public.trial_extension_requests (
  id bigint generated by default as identity primary key,
  organization_id uuid not null references public.organizations(id) on delete cascade,
  requested_by uuid not null references auth.users(id) on delete cascade,
  requested_at timestamptz not null default now()
);

create index if not exists trial_extension_requests_organization_requested_idx
  on public.trial_extension_requests (organization_id, requested_at desc);

alter table public.trial_extension_requests enable row level security;
revoke all on public.trial_extension_requests from anon, authenticated;
grant all on public.trial_extension_requests to service_role;
